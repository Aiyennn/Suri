"""
models/analysis_result.py
=========================
SQLAlchemy ORM model for the ``wound_analysis_results`` table.

Persists the full output of the rule engine for a single wound image,
including the AI classification, risk scoring, recommendations,
referral/emergency flags, and all triggered rule explanations.

Maps to the engine's ``AssessmentResult`` and ``Classification``
Pydantic models.
"""

import uuid
from datetime import datetime, timezone

from sqlalchemy import Boolean, Column, DateTime, Float, ForeignKey, Integer, String, Text
from sqlalchemy.dialects.postgresql import JSON, UUID
from sqlalchemy.orm import relationship

from core.database import Base


class WoundAnalysisDBResult(Base):
    """Complete rule-engine assessment output for a single wound image."""

    __tablename__ = "wound_analysis_results"

    id = Column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        doc="Auto-generated UUID primary key.",
    )
    image_id = Column(
        UUID(as_uuid=True),
        ForeignKey("wound_images.id", ondelete="CASCADE"),
        unique=True,
        nullable=False,
        doc="One-to-one FK to the wound image.",
    )

    # ── AI classification ─────────────────────────────────────────────────
    wound_type = Column(
        String(30),
        nullable=False,
        doc="Wound morphology category from classification.",
    )
    severity = Column(
        String(20),
        nullable=False,
        doc="Clinician-interpretable severity tier.",
    )
    healing_stage = Column(
        String(20),
        nullable=False,
        doc="Current wound-healing phase.",
    )
    confidence = Column(
        Float,
        nullable=False,
        doc="AI model confidence score in [0.0, 1.0].",
    )

    # ── Rule-engine output ────────────────────────────────────────────────
    risk_score = Column(
        Integer,
        nullable=False,
        doc="Cumulative integer risk score from triggered rules.",
    )
    risk_level = Column(
        String(20),
        nullable=False,
        doc="Categorical risk tier: Low, Moderate, High, Critical.",
    )
    recommendations = Column(
        JSON,
        nullable=False,
        doc="Ordered list of recommendation strings.",
    )
    referral_required = Column(
        Boolean,
        nullable=False,
        doc="Whether healthcare-provider referral is advised.",
    )
    emergency = Column(
        Boolean,
        nullable=False,
        doc="Whether an emergency response may be warranted.",
    )
    follow_up = Column(
        String(100),
        nullable=False,
        doc="Recommended follow-up timeframe.",
    )
    triggered_rules = Column(
        JSON,
        nullable=False,
        doc="List of triggered-rule dicts (id, name, reason, score).",
    )
    disclaimer = Column(
        Text,
        nullable=False,
        default=(
            "This assessment is generated by a deterministic rule engine to support "
            "clinical decision-making. It does not constitute a medical diagnosis or "
            "replace the judgment of a licensed healthcare professional."
        ),
        doc="Mandatory clinical-safety disclaimer.",
    )
    created_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
        doc="Timestamp when the analysis was completed.",
    )

    # ── Relationships ─────────────────────────────────────────────────────
    image = relationship(
        "WoundImage",
        back_populates="analysis_result",
    )

    def __repr__(self) -> str:
        return (
            f"<WoundAnalysisDBResult id={self.id!s:.8} "
            f"risk_level={self.risk_level!r} emergency={self.emergency}>"
        )
